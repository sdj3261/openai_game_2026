const TRANSLATIONS = Object.fromEntries(LANGUAGES.map(({ code }) => {
  const stageEntries = Object.entries(STAGES[code]).flatMap(([number, copy]) => [
    [`stage.${number}.title`, copy.title],
    [`stage.${number}.cue`, copy.cue],
    [`stage.${number}.rule`, copy.rule],
  ]);
  return [code, Object.freeze({ ...CORE[code], ...Object.fromEntries(stageEntries) })];
}));

function languageCandidates(input) {
  if (Array.isArray(input)) return input.flatMap(languageCandidates);
  const raw = String(input ?? "").trim().toLowerCase();
  if (!raw) return [];
  const normalized = raw.replaceAll("_", "-");
  return [normalized, normalized.split("-")[0]];
}

export function resolveLanguage(input) {
  return languageCandidates(input).find((candidate) => LANGUAGE_CODES.has(candidate)) || DEFAULT_LANGUAGE;
}

function interpolate(template, params) {
  const values = params && typeof params === "object" ? params : {};
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, name) => (
    Object.hasOwn(values, name) ? String(values[name]) : placeholder
  ));
}

export function t(language, key, params = {}) {
  const resolvedLanguage = resolveLanguage(language);
  const normalizedKey = String(key ?? "");
  const template = TRANSLATIONS[resolvedLanguage]?.[normalizedKey]
    ?? TRANSLATIONS[DEFAULT_LANGUAGE]?.[normalizedKey]
    ?? normalizedKey;
  return interpolate(template, params);
}
